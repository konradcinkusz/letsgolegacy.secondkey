    [Fact]
    public void Unexercised_accepted_clauses_are_named_as_a_limitation_and_regressed_ones_are_marked()
    {
        var sample = SampleVerdict();
        var verdict = sample with
        {
            Clauses = sample.Clauses.Select(c => c.Id switch
            {
                "CART-SHOWS-TOTAL-AND-LINES" => c with { Status = ClauseStatus.Unexercised, Exercised = 0 },
                "TOTAL-NEVER-NEGATIVE" => c with { Status = ClauseStatus.Regressed, Candidate = new Tally { Pass = 4, Fail = 0, Error = 1 } },
                _ => c,
            }).ToList(),
        };

        var html = Render(verdict);

        Assert.Contains("1 accepted clause(s) were not exercised by any request and are not reported as passed: CART-SHOWS-TOTAL-AND-LINES.", html, StringComparison.Ordinal);
        Assert.Contains("<span class=\"badge fail\">regressed</span>", html, StringComparison.Ordinal);
        Assert.Contains("<span class=\"badge review\">unexercised</span>", html, StringComparison.Ordinal);
        Assert.Contains("<span class=\"fail-text\">1 error</span>", html, StringComparison.Ordinal);
    }

    [Fact]
    public void A_run_with_nothing_to_show_says_none_rather_than_leaving_sections_out()
    {
        var sample = SampleVerdict();
        var empty = sample with
        {
            Exchanges = [],
            Clauses = sample.Clauses.Where(c => c.Accepted).Select(c => c with { Status = ClauseStatus.Held }).ToList(),
            Summary = sample.Summary with { Scenarios = null, Clauses = sample.Summary.Clauses with { AbsenceShare = null } },
        };

        var html = Render(empty);

        Assert.Equal(4, html.Split("<p>None.</p>").Length - 1);
        Assert.DoesNotContain("Absence share", html, StringComparison.Ordinal);
        Assert.DoesNotContain("proposed clause(s)", html, StringComparison.Ordinal);
        Assert.DoesNotContain("broken on both sides", html, StringComparison.Ordinal);
        Assert.Contains("Only the recorded traffic was compared: 5 exchange(s). Behaviour", html, StringComparison.Ordinal);
    }

    [Fact]
    public void Every_normalization_rule_and_compare_setting_is_listed()
    {
        var contract = SampleContract().Document with
        {
            Metadata = SampleContract().Document.Metadata with { System = null, Title = null },
            Compare = new CompareSettings { Headers = ["content-type", "x-total"], Html = HtmlCompareMode.Text },
            Normalize = new NormalizeSettings
            {
                Tolerances = [new ToleranceRule { Path = "response.body.json.rate", Relative = 0.02m }],
                Sets = [new SetRule { Path = "response.body.json.tags" }, new SetRule { Path = "response.body.json.items", Key = "sku" }],
                Masks = new MaskSettings { Patterns = [new MaskPattern { Name = "csrf", Regex = "value=\"[^\"]+\"", Replacement = "x" }] },
            },
        };

        var html = Render(contract: contract);

        Assert.Contains("<h1>sample-shop</h1>", html, StringComparison.Ordinal);
        Assert.DoesNotContain("System: ", html, StringComparison.Ordinal);
        Assert.Contains("Response headers compared: <code>content-type</code>, <code>x-total</code>;", html, StringComparison.Ordinal);
        Assert.Contains("HTML pages are compared as text.", html, StringComparison.Ordinal);
        Assert.Contains("Tolerance: <code>response.body.json.rate</code> within ±2.00% of the larger value", html, StringComparison.Ordinal);
        Assert.Contains("Order does not matter: <code>response.body.json.tags</code></li>", html, StringComparison.Ordinal);
        Assert.Contains("Order does not matter: <code>response.body.json.items</code>, elements matched by <code>sku</code>", html, StringComparison.Ordinal);
        Assert.Contains("Masked: <code>csrf</code> — <code>value=&quot;[^&quot;]+&quot;</code>", html, StringComparison.Ordinal);
        Assert.DoesNotContain("Masked: GUIDs", html, StringComparison.Ordinal);
        Assert.DoesNotContain("Masked: ISO-8601", html, StringComparison.Ordinal);
    }

    [Fact]
    public void A_contract_without_normalization_says_only_what_is_compared()
    {
        var contract = SampleContract().Document with { Compare = null, Normalize = null };

        var html = Render(contract: contract);

        Assert.Contains("Response headers compared: <code>content-type</code>, <code>location</code>;", html, StringComparison.Ordinal);
        Assert.Contains("HTML pages are compared only through the values the contract extracts from them", html, StringComparison.Ordinal);
        Assert.DoesNotContain("Ignored:", html, StringComparison.Ordinal);
    }

    [Fact]
    public void A_missing_answer_and_a_clause_regression_are_explained_in_words()
    {
        var verdict = WithExchanges(SampleVerdict(), e => e.Exchange == "ex-000001" ? e with { Reasons = ["missing-result: candidate (timeout)", "clause-regression: TOTAL-NEVER-NEGATIVE", "clause-regression: UNKNOWN-CLAUSE", "something-else"] } : e);

        var html = Render(verdict);

        Assert.Contains("<strong>No answer to compare</strong> from candidate (timeout).", html, StringComparison.Ordinal);
        Assert.Contains("<strong>Clause broken by the candidate</strong>, kept by legacy: <code>TOTAL-NEVER-NEGATIVE</code> — A cart or order total is never negative.", html, StringComparison.Ordinal);
        Assert.Contains("kept by legacy: <code>UNKNOWN-CLAUSE</code>.", html, StringComparison.Ordinal);
        Assert.Contains("<li>something-else</li>", html, StringComparison.Ordinal);
    }

    [Fact]
    public void Null_input_is_refused()
    {
        Assert.Throws<ArgumentNullException>(() => HtmlReport.Render(null!));
    }
}
